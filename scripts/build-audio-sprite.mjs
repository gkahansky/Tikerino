#!/usr/bin/env node
/**
 * Rebuild a lesson's narration sprite (walkthrough.mp3) + the generated
 * offsets module (client/src/narration-audio.ts) from the per-segment mp3s.
 *
 * Run after generating or replacing TTS audio for a narrated lesson:
 *   node scripts/build-audio-sprite.mjs
 *
 * Requires ffmpeg + ffprobe on PATH. Segment files must be named
 * intro.mp3, step-1.mp3, ... under client/public/audio/lessons/<lessonId>/.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const AUDIO_ROOT = resolve(ROOT, 'client/public/audio/lessons');
const OUT_TS = resolve(ROOT, 'client/src/narration-audio.ts');

const durationMs = (file) =>
  Math.round(
    Number(
      execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file], { encoding: 'utf8' }).trim(),
    ) * 1000,
  );

const lessons = readdirSync(AUDIO_ROOT, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name);

const out = {};
for (const lessonId of lessons) {
  const dir = resolve(AUDIO_ROOT, lessonId);
  const files = readdirSync(dir)
    .filter((f) => /^(intro|step-\d+)\.mp3$/.test(f))
    .sort((a, b) => (a === 'intro.mp3' ? -1 : b === 'intro.mp3' ? 1 : Number(a.match(/\d+/)[0]) - Number(b.match(/\d+/)[0])));
  if (files.length === 0) continue;

  // Sample-accurate concat (re-encode), so offsets are just cumulative sums.
  const inputs = files.flatMap((f) => ['-i', resolve(dir, f)]);
  const filter = `${files.map((_, i) => `[${i}:a]`).join('')}concat=n=${files.length}:v=0:a=1,aresample=24000[a]`;
  execFileSync('ffmpeg', ['-y', '-v', 'error', ...inputs, '-filter_complex', filter, '-map', '[a]', '-codec:a', 'libmp3lame', '-b:a', '96k', '-ac', '1', resolve(dir, 'walkthrough.mp3')], { stdio: 'inherit' });

  let offset = 0;
  const segments = {};
  for (const f of files) {
    const duration = durationMs(resolve(dir, f));
    segments[f.replace(/\.mp3$/, '')] = { offsetMs: offset, durationMs: duration };
    offset += duration;
  }
  out[lessonId] = { spriteFile: 'walkthrough.mp3', segments };
  console.log(`${lessonId}: ${files.length} segments, sprite ${offset}ms`);
}

const ts = `/**
 * GENERATED by scripts/build-audio-sprite.mjs - do not edit by hand.
 *
 * One audio sprite per narrated lesson (walkthrough.mp3): all segments back
 * to back in one file, so the player never swaps src on its audio element.
 * Swapping src is what broke narration after the first segment on iOS
 * Safari (Guy, 13 Sep 15:56 IDT: only the intro played, the rest fell back
 * to silent text) - WebKit treats a new src outside a user gesture as a new
 * media load and blocks play(). Seeking one blessed element is safe
 * everywhere. Offsets/durations are ffprobe-measured from the per-segment
 * source mp3s, in play order.
 */
export interface SpriteTiming {
  /** Segment start inside the sprite, milliseconds. */
  offsetMs: number;
  /** Segment length, milliseconds. */
  durationMs: number;
}

export interface LessonSprite {
  spriteFile: string;
  /** Keyed by segment id (intro, step-1, step-2, ...), in play order. */
  segments: Record<string, SpriteTiming>;
}

export const LESSON_SPRITES: Record<string, LessonSprite> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(OUT_TS, ts);
console.log(`wrote ${OUT_TS}`);
